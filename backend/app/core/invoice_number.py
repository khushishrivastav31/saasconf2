    reset_mode = settings.get("cancellation_counter_reset", "yearly")
    counter = settings.get("cancellation_counter_value", 1)
    last_reset = settings.get("cancellation_counter_last_reset")

    now = datetime.now(timezone.utc)
    should_reset = False

    if last_reset is None:
        should_reset = True
    else:
        last_reset_dt = datetime.fromisoformat(last_reset)
        if reset_mode == "yearly":
            if now.year > last_reset_dt.year:
                should_reset = True
        elif reset_mode == "daily":
            days_since_monday = now.weekday()
            last_monday = now - timedelta(days=days_since_monday)
            if last_monday.date() > last_reset_dt.date():
                should_reset = True

    if should_reset:
        counter = 1

    number = template
    number = number.replace("[ConferenceSlug]", conference.slug.upper())
    number = number.replace("[YYYY]", str(now.year))
    number = number.replace("[MM]", str(now.month).zfill(2))
