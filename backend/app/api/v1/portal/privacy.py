# List (caller's own requests)
# ---------------------------------------------------------------------------


@router.get("/me/privacy-requests")
async def list_portal_privacy_requests(
    request: Request,
    db: DbSessionDep,
    page: int = Query(1, ge=1),
    page_size: int = Query(50, ge=1, le=100),
) -> dict[str, Any]:
    """Paginated list of the caller's own privacy requests, newest first."""
    user = await _get_current_portal_user(request, db)

    query = (
        select(PrivacyRequest)
        .where(
            PrivacyRequest.tenant_id == user.tenant_id,
            PrivacyRequest.portal_user_id == user.id,
        )
        .order_by(desc(PrivacyRequest.created_at))
    )

    total_result = await db.execute(
        select(PrivacyRequest.id).where(
            PrivacyRequest.tenant_id == user.tenant_id,
            PrivacyRequest.portal_user_id == user.id,
        )
    )
    total = len(total_result.all())

    page_query = query.offset((page - 1) * page_size).limit(page_size)
    result = await db.execute(page_query)
    rows = result.scalars().all()

    items = [_to_portal_response(pr).model_dump(mode="json") for pr in rows]
    pages = (total + page_size - 1) // page_size if total else 0
    return {
        "items": items,
        "total": total,
        "page": page,
        "page_size": page_size,
        "pages": pages,
    }


# ---------------------------------------------------------------------------
# Detail
# ---------------------------------------------------------------------------


@router.get("/me/privacy-requests/{request_id}", response_model=PortalPrivacyRequestResponse)
async def get_portal_privacy_request(
    request_id: UUID,
    request: Request,
    db: DbSessionDep,
) -> PortalPrivacyRequestResponse:
    """Fetch detail for one of the caller's own privacy requests."""
    user = await _get_current_portal_user(request, db)
    pr = await _load_for_portal_user(db, request_id, user)
    return _to_portal_response(pr)


# ---------------------------------------------------------------------------
# Download (export ZIP, 7-day window)
# ---------------------------------------------------------------------------


@router.get("/me/privacy-requests/{request_id}/download")
async def download_portal_privacy_export(
    request_id: UUID,
    request: Request,
    db: DbSessionDep,
) -> StreamingResponse:
    """Stream the Art. 15 export ZIP. 410 Gone after the 7-day window."""
    user = await _get_current_portal_user(request, db)
    pr = await _load_for_portal_user(db, request_id, user)

    if pr.request_type != PrivacyRequestType.EXPORT.value:
        raise ValidationError("Only export requests expose a download link.")
    if pr.status != PrivacyRequestStatus.COMPLETED.value:
        raise ValidationError(f"Export is not available to download in status '{pr.status}'")
    if pr.executed_at is None:
        raise ValidationError("Export has no executed_at timestamp; create a new export.")

    executed_at = pr.executed_at
    if executed_at.tzinfo is None:
        executed_at = executed_at.replace(tzinfo=UTC)
    if datetime.now(UTC) - executed_at > timedelta(days=DOWNLOAD_WINDOW_DAYS):
        raise HTTPException(
            status_code=410,
            detail="Download window expired. Please create a new export.",
        )

    emails = pr.subject_emails
    if not emails:
        raise ValidationError("Privacy request has no subject emails on file.")

    blob, _manifest = await build_export(db, user.tenant_id, emails, mode="portal")

    first_hash = pr.subject_email_hashes[0] if pr.subject_email_hashes else None
    db.add(
        BaseService.create_audit_log(
            tenant_id=user.tenant_id,
            user_id=None,
            action=AuditAction.PRIVACY_REQUEST_PORTAL_DOWNLOAD,
            resource_type="privacy_request",
            resource_id=pr.id,
            ip_address=get_client_ip(request),
            user_agent=request.headers.get("User-Agent"),
            subject_email_hash=first_hash,
        )
    )
    await db.commit()

    filename = f"my-data-export-{pr.id}.zip"

    def _iter() -> Any:
        yield blob

    return StreamingResponse(
        _iter(),
        media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
