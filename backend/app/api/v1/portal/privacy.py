"""Portal self-service privacy endpoints (GDPR Phase 4).

Lets a signed-in ``PortalUser`` exercise their own Art. 15 (export) and
Art. 17 (erasure) rights without having to email the tenant.

Endpoints (all require a valid portal access token):

* ``POST /portal/me/privacy-requests`` — creates a request. ``request_type
  == "export"`` runs inline (no admin approval) and returns a short-lived
  download URL. ``request_type == "erasure"`` is created in
  ``pending_review`` state and queued for the tenant admin exactly like
  an admin-initiated row — actual deletion still goes through Phase 3
  execute-erasure with the human-in-the-loop preview.
* ``GET  /portal/me/privacy-requests`` — list the caller's own requests.
* ``GET  /portal/me/privacy-requests/{id}`` — detail for one of them.
* ``GET  /portal/me/privacy-requests/{id}/download`` — stream the ZIP
  generated by the most recent export (7-day window; 410 afterwards).

Security rails:

* ``subject_emails`` is always the portal user's own email. We never
  accept it from the client — a logged-in portal user cannot file a
  request for somebody else's data.
* All list/detail queries are scoped to ``portal_user_id == user.id``.
* Export uses ``build_export(..., mode="portal")`` which drives off
  ``PORTAL_EXPORT_FIELDS`` — an explicit allowlist (see
  ``app/core/gdpr/lookups.py``) so internal staff notes and comment
  fields never leak into the download.
* Rate limits: 2 exports/day and 1 erasure/day per IP — exports
  are cheap to run but can be farmed as a reconnaissance vector,
  erasure is irreversible.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta
from typing import Any
from uuid import UUID

from fastapi import APIRouter, HTTPException, Query, Request
from fastapi.responses import StreamingResponse
from sqlalchemy import desc, select

from app.api.v1.portal_auth import _get_current_portal_user
from app.core.dependencies import DbSessionDep, get_client_ip
from app.core.exceptions import NotFoundError, ValidationError
from app.core.gdpr.export import build_export
from app.core.rate_limiter import limiter
from app.core.security.pii_crypto import read_pii
from app.models.audit import AuditAction
from app.models.portal_user import PortalUser
from app.models.privacy_request import (
    PrivacyRequest,
    PrivacyRequestStatus,
    PrivacyRequestType,
)
from app.schemas.privacy_request import (
    PortalExportCreateResponse,
    PortalPrivacyRequestCreate,
    PortalPrivacyRequestResponse,
)
from app.services.base import BaseService

router = APIRouter()

DOWNLOAD_WINDOW_DAYS = 7


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _to_portal_response(pr: PrivacyRequest) -> PortalPrivacyRequestResponse:
    """Build the trimmed portal-facing response (no staff IDs, no tenant_id)."""
    return PortalPrivacyRequestResponse(
        id=pr.id,
        request_type=PrivacyRequestType(pr.request_type),
        status=PrivacyRequestStatus(pr.status),
        created_at=pr.created_at,
        reviewed_at=pr.reviewed_at,
        executed_at=pr.executed_at,
        completion_artifact_url=pr.completion_artifact_url,
        rejection_reason=pr.rejection_reason,
        notes=pr.notes,
    )


def _portal_user_email(user: PortalUser) -> str:
    """Read the decrypted email or raise if the row is missing one."""
    email = read_pii(user, "email")
    if not email:
        raise ValidationError("Your account has no email on file.")
    return email.strip().lower()


async def _load_for_portal_user(
    db: Any,
    request_id: UUID,
    user: PortalUser,
) -> PrivacyRequest:
    """Fetch one privacy request for the calling portal user or raise 404."""
    result = await db.execute(
        select(PrivacyRequest).where(
            PrivacyRequest.id == request_id,
            PrivacyRequest.tenant_id == user.tenant_id,
            PrivacyRequest.portal_user_id == user.id,
        )
    )
    pr = result.scalar_one_or_none()
    if not pr:
        raise NotFoundError("Privacy request not found")
    return pr


# ---------------------------------------------------------------------------
# Create (export runs inline, erasure queues for admin review)
# ---------------------------------------------------------------------------


@router.post("/me/privacy-requests")
@limiter.limit("3/day")
async def create_portal_privacy_request(
    request: Request,
    payload: PortalPrivacyRequestCreate,
    db: DbSessionDep,
) -> Any:
    """Create a privacy request for the current portal user.

    Response shape depends on the type:
    * ``export`` → :class:`PortalExportCreateResponse` (includes a ready
      ``download_url``).
    * ``erasure`` → :class:`PortalPrivacyRequestResponse` (queued in
      ``pending_review`` status).
    """
    user = await _get_current_portal_user(request, db)
    email = _portal_user_email(user)
    ip_address = get_client_ip(request)
    user_agent = request.headers.get("User-Agent")

    pr = PrivacyRequest(
        tenant_id=user.tenant_id,
        request_type=payload.request_type.value,
        portal_user_id=user.id,
        notes=payload.notes,
    )
    pr.subject_emails = [email]
    db.add(pr)
    await db.flush()

    first_hash = pr.subject_email_hashes[0] if pr.subject_email_hashes else None

    db.add(
        BaseService.create_audit_log(
            tenant_id=user.tenant_id,
            user_id=None,
            action=AuditAction.PRIVACY_REQUEST_PORTAL_CREATE,
            resource_type="privacy_request",
            resource_id=pr.id,
            details={
                "request_type": pr.request_type,
                "portal_user_id": str(user.id),
            },
            ip_address=ip_address,
            user_agent=user_agent,
            subject_email_hash=first_hash,
        )
    )

    if payload.request_type == PrivacyRequestType.ERASURE:
        await db.commit()
        await db.refresh(pr)
        return _to_portal_response(pr)

    # Export: run the build inline so the user gets an immediate download.
    _blob, manifest = await build_export(db, user.tenant_id, [email], mode="portal")

    now = datetime.now(UTC)
    pr.status = PrivacyRequestStatus.COMPLETED.value
    pr.executed_at = now
    pr.reviewed_at = now
    pr.execution_manifest = manifest
    pr.completion_artifact_url = f"/api/v1/portal/me/privacy-requests/{pr.id}/download"

    db.add(
        BaseService.create_audit_log(
            tenant_id=user.tenant_id,
            user_id=None,
            action=AuditAction.PRIVACY_REQUEST_PORTAL_EXPORT,
            resource_type="privacy_request",
            resource_id=pr.id,
            details={"record_counts": manifest.get("record_counts", {})},
            ip_address=ip_address,
            user_agent=user_agent,
            subject_email_hash=first_hash,
        )
    )
    await db.commit()
    await db.refresh(pr)

    return PortalExportCreateResponse(
        id=pr.id,
        status=PrivacyRequestStatus(pr.status),
        download_url=pr.completion_artifact_url or "",
        record_counts=manifest.get("record_counts", {}),
        executed_at=now,
    )


