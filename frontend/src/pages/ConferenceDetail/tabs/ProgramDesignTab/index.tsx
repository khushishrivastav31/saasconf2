import { useState, useEffect, useRef } from 'react';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import {
  DndContext,
  DragOverlay,
  closestCenter,
  PointerSensor,
  useSensor,
  useSensors,
  type DragStartEvent,
  type DragEndEvent,
} from '@dnd-kit/core';
import api from '../../../../config/api';
import { queryKeys } from '../../../../config/queryKeys';
import type { Conference, SessionType, ProgramSession } from '../../../../types';
import { parseApiError } from '../../../../utils/apiError';
import { LoadingSpinner } from '../../../../components/common/LoadingSpinner';
import { useToast } from '../../../../components/Toast';

import { useProgramDays, useProgramGrid } from './hooks/useProgramGrid';
import { useProgramMutations } from './hooks/useProgramMutations';
import { useProgramDesignHandlers } from './hooks/useProgramDesignHandlers';
import DayTabs from './DayTabs';
import ProgramGrid from './ProgramGrid';
import SessionModal from './SessionModal';
import { SessionCardOverlay } from './SessionCard';
import ConfirmDialog from '../../../../components/ConfirmDialog';

interface ProgramDesignTabProps {
  conference: Conference;
  isAdmin: boolean;
}

export default function ProgramDesignTab({ conference, isAdmin }: ProgramDesignTabProps) {
  const [selectedDayId, setSelectedDayId] = useState<string | null>(null);
  const [editingSession, setEditingSession] = useState<ProgramSession | null>(null);
  const [activeDragId, setActiveDragId] = useState<string | null>(null);
  const [activeDragData, setActiveDragData] = useState<unknown>(null);
  const [pendingDeleteSessionId, setPendingDeleteSessionId] = useState<string | null>(null);
  const { showToast } = useToast();

  // Configure drag sensors
  const sensors = useSensors(
    useSensor(PointerSensor, {
      activationConstraint: {
        distance: 8,
      },
    })
  );

  // Fetch program days
  const {
    data: daysData,
    isLoading: daysLoading,
    isError: daysError,
  } = useProgramDays({
    conferenceId: conference.id,
  });

  // Fetch grid data for selected day
  const { data: gridData, isLoading: gridLoading } = useProgramGrid({
    conferenceId: conference.id,
    dayId: selectedDayId,
    enabled: !!selectedDayId,
  });

  // Fetch session types for session modal
  const { data: sessionTypesData } = useQuery({
    queryKey: queryKeys.program.sessionTypes(conference.id),
    queryFn: async () => {
      const response = await api.get<{ items: SessionType[]; total: number }>(
        `/conferences/${conference.id}/settings/session-types`
      );
      return response.data.items;
    },
  });

  // Mutations
  const mutations = useProgramMutations(conference.id);
  const queryClient = useQueryClient();

  // Auto-generate program days from conference dates when none exist
  const hasAutoGenerated = useRef(false);
  useEffect(() => {
    if (hasAutoGenerated.current || !daysData) return;
    if (daysData.items.length > 0) return; // days already exist
    if (!conference.start_date || !conference.end_date) return; // no dates set

    hasAutoGenerated.current = true;
    api
      .post(`/conferences/${conference.id}/program/days/generate`, {})
      .then((res) => {
        if (res.data.created?.length > 0) {
          queryClient.invalidateQueries({ queryKey: queryKeys.program.days(conference.id) });
        }
      })
      .catch((err) => console.error('Failed to auto-generate program days:', err));
  }, [daysData, conference, queryClient]);

  // Auto-select first day when days load
  useEffect(() => {
    if (daysData?.items && daysData.items.length > 0 && !selectedDayId) {
      setSelectedDayId(daysData.items[0].id);
    }
  }, [daysData, selectedDayId]);

  const {
    handleCreateDay,
    handleUpdateDay,
    handleDeleteDay,
    handleUpdateSlot,
    handleDeleteSlot,
    handleUpdateTrack,
    handleDeleteTrack,
    handleUpdateSession,
    handleDeleteSession,
    confirmDeleteSession,
    handleResizeSession,
    handleQuickAddTrack,
    handleQuickAddSlot,
    handleMergeCells,
  } = useProgramDesignHandlers({
    mutations,
    showToast,
    daysData,
    gridData,
    selectedDayId,
    setSelectedDayId,
    setEditingSession,
    pendingDeleteSessionId,
    setPendingDeleteSessionId,
  });

  // Drag and drop handlers
  const handleDragStart = (event: DragStartEvent) => {
    setActiveDragId(event.active.id as string);
    setActiveDragData(event.active.data.current);
  };

  const handleDragEnd = async (event: DragEndEvent) => {
    setActiveDragId(null);
    setActiveDragData(null);

    const { active, over } = event;
    if (!over || !active.data.current) return;

    const dragData = active.data.current;
    const dropData = over.data.current as { slotId: string; trackId: string | null };

    if (!dropData?.slotId) return;

    try {
      // Moving existing session
      if (dragData.type === 'session') {
        await mutations.moveSession.mutateAsync({
          sessionId: dragData.session.id,
          data: {
            start_slot_id: dropData.slotId,
            start_track_id: dropData.trackId || undefined,
          },
        });
        return;
      }
    } catch (error) {
      showToast(parseApiError(error, 'Failed to create/move session'));
    }
  };

  // Loading state
  if (daysLoading) {
    return (
      <div className="flex justify-center py-12">
        <LoadingSpinner />
      </div>
    );
  }

  if (daysError) {
    return (
      <div className="text-center py-8 text-red-500 dark:text-red-400">
        Failed to load data. Please try again.
      </div>
    );
  }

  const days = daysData?.items || [];
  const slots = gridData?.slots || [];
  const tracks = gridData?.tracks || [];
  const sessions = gridData?.sessions || [];
  const sessionTypes = sessionTypesData || [];
  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between">
        <h2 className="text-lg font-semibold text-gray-900 dark:text-gray-100">Program Design</h2>
      </div>

      {/* Day tabs */}
      <DayTabs
        days={days}
        selectedDayId={selectedDayId}
        onSelectDay={setSelectedDayId}
        onCreateDay={handleCreateDay}
        onUpdateDay={handleUpdateDay}
        onDeleteDay={handleDeleteDay}
        isAdmin={isAdmin}
        daysAutoGenerated={!!conference.start_date && !!conference.end_date}
      />

      {selectedDayId && (
        <>
          {/* Main grid area */}
          {gridLoading ? (
            <div className="flex justify-center py-12">
              <LoadingSpinner />
            </div>
          ) : (
            <DndContext
              sensors={sensors}
              collisionDetection={closestCenter}
              onDragStart={handleDragStart}
              onDragEnd={handleDragEnd}
            >
              <div
                className="overflow-x-auto"
                style={{ height: Math.max(400, 48 + slots.length * 60 + (isAdmin ? 48 : 0)) }}
              >
                <ProgramGrid
                  slots={slots}
                  tracks={tracks}
                  sessions={sessions}
                  onSessionClick={(session) => setEditingSession(session)}
                  onDeleteSession={handleDeleteSession}
                  onResizeSession={handleResizeSession}
                  onUpdateSlot={handleUpdateSlot}
                  onDeleteSlot={handleDeleteSlot}
                  onUpdateTrack={handleUpdateTrack}
                  onDeleteTrack={handleDeleteTrack}
                  onMergeCells={isAdmin ? handleMergeCells : undefined}
                  onAddTrack={isAdmin ? handleQuickAddTrack : undefined}
                  onAddSlot={isAdmin ? handleQuickAddSlot : undefined}
                  isAdmin={isAdmin}
                  activeSessionId={activeDragId}
                />
              </div>

              {/* Drag overlay */}
              <DragOverlay>
                {activeDragId && activeDragData
                  ? (() => {
                      const data = activeDragData as Record<string, unknown>;
                      if (data.type === 'session') {
                        return <SessionCardOverlay session={data.session as ProgramSession} />;
                      }
                      return null;
                    })()
                  : null}
              </DragOverlay>
            </DndContext>
          )}
        </>
      )}

      {/* No day selected state */}
      {!selectedDayId && days.length === 0 && (
        <div className="flex flex-col items-center justify-center py-12 bg-gray-50 dark:bg-gray-900 rounded-lg border-2 border-dashed border-gray-300 dark:border-gray-600">
          <svg
            className="w-12 h-12 text-gray-400 dark:text-gray-500 mb-4"
            fill="none"
            stroke="currentColor"
            viewBox="0 0 24 24"
          >
            <path
              strokeLinecap="round"
              strokeLinejoin="round"
              strokeWidth={2}
              d="M8 7V3m8 4V3m-9 8h10M5 21h14a2 2 0 002-2V7a2 2 0 00-2-2H5a2 2 0 00-2 2v12a2 2 0 002 2z"
            />
          </svg>
          <h3 className="text-lg font-medium text-gray-900 dark:text-gray-100 mb-2">
            No Program Days
          </h3>
          <p className="text-sm text-gray-500 dark:text-gray-400 mb-4 text-center max-w-md">
            Add program days to start building your conference schedule.
          </p>
        </div>
      )}

      {/* Session edit modal */}
      <SessionModal
        open={!!editingSession}
        onClose={() => setEditingSession(null)}
        session={editingSession}
        sessionTypes={sessionTypes}
        slots={slots}
        maxSlotSpan={Math.max(slots.length, 1)}
        maxTrackSpan={Math.max(tracks.length, 1)}
        onUpdate={handleUpdateSession}
        onDelete={handleDeleteSession}
        isAdmin={isAdmin}
      />

      <ConfirmDialog
        open={!!pendingDeleteSessionId}
        title="Delete session with assigned paper"
        message="This session has a paper assigned. Deleting it will automatically unassign the paper. Do you want to continue?"
        confirmLabel="Delete"
        cancelLabel="Cancel"
        variant="warning"
        onConfirm={confirmDeleteSession}
        onCancel={() => setPendingDeleteSessionId(null)}
      />
    </div>
  );
}
