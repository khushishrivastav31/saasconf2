#!/usr/bin/env node
/**
 * Generate TypeScript types from the FastAPI OpenAPI schema.
 *
 * Why a standalone script:
 *   - Hitting a running backend on :8000 forces a dev-env dependency.
 *   - The backend can emit its schema offline with
 *     ``python -c "from app.main import app; print(json.dumps(app.openapi()))"``,
 *     so we keep the pipeline hermetic and reproducible.
 *
 * Output:  frontend/src/types/api.generated.ts (committed; reviewable)
 *
 * Use in CI:
 *   ``node scripts/generate-api-types.mjs --check``
 *   Re-runs the codegen, then asserts ``git diff`` is empty. Drift between
 *   the backend schema and the checked-in types fails the build.
 */

import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import prettier from 'prettier';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const FRONTEND_DIR = resolve(__dirname, '..');
const BACKEND_DIR = resolve(FRONTEND_DIR, '..', 'backend');
const OUTPUT_PATH = resolve(FRONTEND_DIR, 'src', 'types', 'api.generated.ts');

function fetchSchema() {
  const pythonBin = resolve(BACKEND_DIR, 'venv', 'bin', 'python');
  const python = existsSync(pythonBin) ? pythonBin : 'python3';
  const result = spawnSync(
    python,
    ['-c', 'from app.main import app; import json, sys; json.dump(app.openapi(), sys.stdout)'],
    { cwd: BACKEND_DIR, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
  );
  if (result.status !== 0) {
    console.error('Failed to load FastAPI schema:');
    console.error(result.stderr);
    process.exit(1);
  }
  try {
    return JSON.parse(result.stdout);
  } catch (err) {
    console.error('Schema was not valid JSON:', err);
    console.error(result.stdout.slice(0, 500));
    process.exit(1);
  }
}

async function run() {
  const schema = fetchSchema();
  const ast = await openapiTS(schema, {
    exportType: true,
    enum: false,
    immutable: false,
    defaultNonNullable: false,
  });
  const raw =
    '// AUTO-GENERATED by scripts/generate-api-types.mjs — DO NOT EDIT BY HAND.\n' +
    '// Run `npm run gen:api` to refresh after backend schema changes.\n\n' +
    astToString(ast);
  // Run through Prettier so CI output matches what lint-staged would produce
  // on commit — otherwise `--check` drifts on quote style + indent alone.
  const prettierConfig = (await prettier.resolveConfig(OUTPUT_PATH)) ?? {};
  const body = await prettier.format(raw, { ...prettierConfig, parser: 'typescript' });
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });

  if (process.argv.includes('--check')) {
    const previous = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, 'utf8') : '';
    if (previous !== body) {
      writeFileSync(OUTPUT_PATH, body);
      console.error(
        'api.generated.ts is out of date. Run `npm run gen:api` and commit the result.',
      );
      process.exit(2);
    }
    console.log('api.generated.ts is in sync with the backend schema.');
    return;
  }

  writeFileSync(OUTPUT_PATH, body);
  console.log(`Wrote ${OUTPUT_PATH}`);
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
